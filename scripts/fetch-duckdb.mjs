#!/usr/bin/env node
// Ensures prebuilt DuckDB static archives for the current host are staged at
//   src-tauri/libs/<rust-triple>/
// and prints `DUCKDB_LIB_DIR=<absolute path>` on the last stdout line.
//
// The DuckDB version is derived from the *resolved* libduckdb-sys version in
// src-tauri/Cargo.lock (duckdb-rs encodes it as 1.MAJOR_MINOR_PATCH.x), so a
// `cargo update` that bumps duckdb automatically fetches matching archives.
//
// Windows MSVC is intentionally skipped (exit 0): the official static-libs
// archives are MinGW-only, so Windows builds use `--features source-bundled`
// (compile from source) instead.
import { spawnSync } from "node:child_process";
import { createWriteStream, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { Readable } from "node:stream";
import { finished } from "node:stream/promises";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const libsRoot = join(root, "src-tauri", "libs");
const log = (m) => console.error(`[fetch-duckdb] ${m}`);
const GENERATED_MARKER = "# AUTO-GENERATED by scripts/fetch-duckdb.mjs — do not edit.";

function hostTriple() {
  if (process.env.DUCKDB_TRIPLE) return process.env.DUCKDB_TRIPLE;
  const r = spawnSync("rustc", ["-vV"], { encoding: "utf8" });
  const m = r.status === 0 && r.stdout.match(/^host:\s*(\S+)/m);
  if (m) return m[1];
  const p = process.platform, a = process.arch;
  if (p === "darwin" && a === "arm64") return "aarch64-apple-darwin";
  if (p === "darwin" && a === "x64") return "x86_64-apple-darwin";
  if (p === "linux" && a === "x64") return "x86_64-unknown-linux-gnu";
  if (p === "linux" && a === "arm64") return "aarch64-unknown-linux-gnu";
  if (p === "win32" && a === "x64") return "x86_64-pc-windows-msvc";
  if (p === "win32" && a === "arm64") return "aarch64-pc-windows-msvc";
  throw new Error(`cannot determine rust target triple for ${p}/${a}`);
}

function duckdbVersion() {
  const lock = readFileSync(join(root, "src-tauri", "Cargo.lock"), "utf8");
  const m = lock.match(/name = "libduckdb-sys"\nversion = "([^"]+)"/);
  if (!m) throw new Error("libduckdb-sys not found in src-tauri/Cargo.lock");
  const encoded = Number(m[1].split(".")[1]); // 1.MAJOR_MINOR_PATCH.x
  const major = Math.floor(encoded / 10000);
  const minor = Math.floor(encoded / 100) % 100;
  const patch = encoded % 100;
  return `${major}.${minor}.${patch}`;
}

function archiveFor(triple) {
  const table = {
    "x86_64-apple-darwin": "static-libs-osx-amd64.zip",
    "aarch64-apple-darwin": "static-libs-osx-arm64.zip",
    "x86_64-unknown-linux-gnu": "static-libs-linux-amd64.zip",
    "aarch64-unknown-linux-gnu": "static-libs-linux-arm64.zip",
  };
  return table[triple] ?? null;
}

async function download(url, dest) {
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) throw new Error(`download failed: ${res.status} ${res.statusText} for ${url}`);
  const tmp = `${dest}.download`;
  const out = createWriteStream(tmp);
  await finished(Readable.fromWeb(res.body).pipe(out));
  renameSync(tmp, dest);
}

function extract(zip, dir) {
  for (const cmd of [
    ["unzip", ["-o", "-q", zip, "-d", dir]],
    ["tar", ["-xf", zip, "-C", dir]],
  ]) {
    const r = spawnSync(cmd[0], cmd[1], { stdio: "inherit" });
    if (r.status === 0) return;
  }
  throw new Error(`could not extract ${zip} (need 'unzip' or 'tar' on PATH)`);
}

const triple = hostTriple();
const archive = archiveFor(triple);
if (!archive) {
  log(`${triple}: no prebuilt static archive (Windows uses --features source-bundled); nothing to fetch.`);
  process.exit(0);
}
const version = duckdbVersion();
const dir = join(libsRoot, triple);
const marker = join(dir, ".fetch-ok");
const stamp = `${version}\n${archive}\n`;
if (existsSync(marker) && readFileSync(marker, "utf8") === stamp && existsSync(join(dir, "libduckdb_static.a"))) {
  log(`cache hit: ${dir} (${version})`);
} else {
  const url = `https://github.com/duckdb/duckdb/releases/download/v${version}/${archive}`;
  log(`downloading ${url}`);
  mkdirSync(dir, { recursive: true });
  const zip = join(dir, archive);
  await download(url, zip);
  extract(zip, dir);
  if (!existsSync(join(dir, "libduckdb_static.a"))) {
    throw new Error(`archive did not contain libduckdb_static.a: ${archive}`);
  }
  writeFileSync(marker, stamp);
  log(`staged ${dir} (${version})`);
}

// Persist the resolved static-link environment for bare `cargo ...` /
// `npx tauri ...` invocations that bypass `scripts/with-duckdb.mjs`
// (ambient env that cargo would otherwise never see: a downstream build.rs
// cannot set variables for libduckdb-sys's own build script, which runs
// first and needs DUCKDB_LIB_DIR itself to emit its search path).
// Explicitly exported variables still win (`force` defaults to false), and
// `--features source-bundled` builds ignore both keys.
writeCargoConfig(dir);
console.log(`DUCKDB_LIB_DIR=${dir}`);

function tomlPath(value) {
  if (!value.includes("'")) return `'${value}'`;
  return JSON.stringify(value);
}

function writeCargoConfig(libDir) {
  // NOTE: cargo discovers `.cargo/config.toml` by walking *up* from the
  // current working directory, not from the manifest directory — so this
  // must live at the repo root (visible both from `npm run …` at the root
  // and from `cargo …` inside `src-tauri/`), not in `src-tauri/.cargo/`.
  const cargoDir = join(root, ".cargo");
  const configPath = join(cargoDir, "config.toml");
  if (existsSync(configPath)) {
    const current = readFileSync(configPath, "utf8");
    if (!current.includes(GENERATED_MARKER)) {
      log(`leaving existing ${configPath} alone (not generated by fetch-duckdb.mjs)`);
      return;
    }
  }
  mkdirSync(cargoDir, { recursive: true });
  writeFileSync(
    configPath,
    `${GENERATED_MARKER}\n` +
      `# Lets plain \`cargo build\` / \`npx tauri build\` link the staged archives\n` +
      `# without going through scripts/with-duckdb.mjs. Regenerated on every fetch.\n` +
      `[env]\n` +
      `DUCKDB_LIB_DIR = ${tomlPath(libDir)}\n` +
      `DUCKDB_STATIC = { value = "1", force = false }\n`,
  );
  log(`wrote ${configPath}`);
}
